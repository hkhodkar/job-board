export function buildSeedJobs(now: Date = new Date()): Job[] {
  return SEEDS.map(({ salary, hoursAgo, niceToHave, ...seed }) => ({
    ...seed,
    salaryMin: salary[0],
    salaryMax: salary[1],
    postedAt: new Date(now.getTime() - hoursAgo * HOUR).toISOString(),
    niceToHave: niceToHave ?? [],
    benefits: BENEFITS[seed.companyId] ?? [],
  }));
}
